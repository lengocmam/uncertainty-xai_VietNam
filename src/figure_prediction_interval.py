"""
Figure 2 — Prediction interval visualization cho GEFCom2014 (a) và OPSD (b).

QUY TAC CHON KHACH QUAN (ghi trong caption, khong tu chon tuan dep):
  - Seed: chon seed co main_coverage GAN MEDIAN nhat trong 5 seed (khong
    phai seed dep nhat) - doc tu multiseed_method_comparison_{name}.csv.
  - Tuan ve: 168 diem DAU TIEN cua tap test (temporally held-out), tuc
    "the first complete seven-day period in the temporally held-out test set".

Yeu cau: da chay multi_seed_method_comparison.py (co predictions_*.csv
va multiseed_method_comparison_*.csv).
"""

import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

RESULTS_DIR = os.path.join("results", "tables")
FIGURES_DIR = os.path.join("results", "figures")
os.makedirs(FIGURES_DIR, exist_ok=True)

TARGET_HOURS_COVERED = 7 * 24  # 7 ngay, tinh theo GIO - so diem thuc te phu thuoc do phan giai du lieu


def infer_window_size(timestamps: pd.Series) -> int:
    """Tu dong xac dinh do phan giai du lieu (theo gio hay 30 phut) va tra ve
    so diem can lay de du 7 ngay - KHONG hardcode 168, tranh sai neu du lieu
    thuc te la 30 phut (can 336 diem) thay vi theo gio."""
    ts_sorted = pd.to_datetime(timestamps).sort_values()
    diffs = ts_sorted.diff().dropna()
    step_minutes = diffs.mode().iloc[0].total_seconds() / 60
    n_points = int(round(TARGET_HOURS_COVERED * 60 / step_minutes))
    print(f"    Do phan giai du lieu phat hien: {step_minutes:.0f} phut/diem "
          f"-> can {n_points} diem de du 7 ngay")
    return n_points


def select_median_coverage_seed(name: str) -> int:
    """Chon seed co main_coverage gan median nhat trong 5 seed - QUY TAC
    KHACH QUAN, khong chon tay theo 'nhin dep'."""
    ms = pd.read_csv(os.path.join(RESULTS_DIR, f"multiseed_method_comparison_{name}.csv"))
    median_cov = ms["main_coverage"].median()
    idx = (ms["main_coverage"] - median_cov).abs().idxmin()
    chosen_seed = int(ms.loc[idx, "seed"])
    print(f"  [{name}] 5 coverage: {ms['main_coverage'].round(4).tolist()} "
          f"-> median={median_cov:.4f} -> chon seed={chosen_seed} "
          f"(coverage={ms.loc[idx, 'main_coverage']:.4f})")
    return chosen_seed


def get_first_week_window(name: str, seed: int) -> pd.DataFrame:
    pred = pd.read_csv(os.path.join(RESULTS_DIR, f"predictions_{name}.csv"))
    pred["timestamp"] = pd.to_datetime(pred["timestamp"])
    subset = pred[(pred["method"] == "GRU+CP") & (pred["seed"] == seed)].sort_values("timestamp")
    n_points = infer_window_size(subset["timestamp"])
    window = subset.iloc[:n_points].copy()
    assert len(window) == n_points, (
        f"Test set qua ngan ({len(subset)} dong) de lay du {n_points} diem - kiem tra lai du lieu.")
    return window


def plot_panel(ax, window: pd.DataFrame, title: str):
    ts = window["timestamp"]
    ax.plot(ts, window["y_true"], color="black", linewidth=1.3, label="Ground truth", zorder=3)
    ax.plot(ts, window["q50"], color="tab:blue", linewidth=1.3, label="Median forecast (q=0.50)", zorder=3)
    ax.fill_between(ts, window["lower_bound_final"], window["upper_bound_final"],
                     color="tab:blue", alpha=0.2, label="90% calibrated interval", zorder=1)

    misses = window[window["covered_90"] == 0]
    ax.scatter(misses["timestamp"], misses["y_true"], color="red", s=28, zorder=4,
               marker="o", label=f"Miss (n={len(misses)})")

    ax.set_title(title, fontsize=10)
    ax.set_xlabel("Time")
    ax.set_ylabel("Load")
    ax.tick_params(axis="x", rotation=30, labelsize=8)
    ax.tick_params(axis="y", labelsize=8)


def main():
    seed_gefcom = select_median_coverage_seed("gefcom2014")
    seed_opsd = select_median_coverage_seed("opsd")

    window_gefcom = get_first_week_window("gefcom2014", seed_gefcom)
    window_opsd = get_first_week_window("opsd", seed_opsd)

    fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))
    plot_panel(axes[0], window_gefcom,
               f"(a) GEFCom2014 (seed={seed_gefcom}, median-coverage run)")
    plot_panel(axes[1], window_opsd,
               f"(b) OPSD (seed={seed_opsd}, median-coverage run)")
    axes[0].legend(fontsize=7, loc="upper right")
    axes[1].legend(fontsize=7, loc="upper right")

    fig.suptitle("Figure 2: 90% Conformal Prediction Intervals — First Complete 7-Day "
                  "Window in the Held-Out Test Set", fontsize=11)
    plt.tight_layout()
    out_path = os.path.join(FIGURES_DIR, "figure2_prediction_intervals.png")
    plt.savefig(out_path, dpi=200)
    plt.close(fig)

    print(f"\nDa luu: {out_path}")
    print("\nCAPTION GOI Y (dung dung nguyen van, da sua loi khoang trang va lam ro 'seed'):")
    print(f'"Figure 2. Calibrated nominal 90% prediction intervals generated by GRU+CP for '
          f'(a) GEFCom2014 and (b) OPSD. For each dataset, the displayed run is the seed whose '
          f'empirical coverage is closest to the median coverage across five independent seeds '
          f'(seed {seed_gefcom} for GEFCom2014, seed {seed_opsd} for OPSD; seed denotes the random '
          f'initialization / run identifier, not a data index). The window is the first complete '
          f'seven-day period in the temporally held-out test set and was selected a priori. The '
          f'blue line denotes the median forecast, the shaded band denotes the calibrated '
          f'interval, and red markers indicate observations outside the interval."')


if __name__ == "__main__":
    main()